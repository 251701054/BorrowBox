#!/usr/bin/env node
'use strict';
// BorrowBox Pinterest-assisted photo selector (Node.js 18+).
// Pinterest does not expose a public, reliable image download API.
// This script creates an offline selection page linking to Pinterest searches.
// Save photos you have permission to use as 01.jpg ... 50.jpg in frontend/images/equipment/.
// Rerun this script to update the app's image map. No database changes required.
const fs = require('node:fs/promises');
const path = require('node:path');
const ROOT = __dirname;
const FRONTEND = path.join(ROOT, 'frontend');
const IMAGE_DIR = path.join(FRONTEND, 'images', 'equipment');
const PLAN_PATH = path.join(ROOT, 'equipment-photo-plan.json');
const MAP_PATH = path.join(FRONTEND, 'equipment-photos.js');
const REVIEW_PATH = path.join(ROOT, 'pinterest-photo-review.html');
const CSV_PATH = path.join(ROOT, 'equipment-pinterest-links.csv');
const EXTS = ['.jpg', '.jpeg', '.png', '.webp'];
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const csv = s => /[,\r\n"]/.test(String(s ?? '')) ? '"' + String(s).replace(/"/g,'""') + '"' : String(s ?? '');
async function existingImage(id) {
  for (const ext of EXTS) {
    const filename = `${String(id).padStart(2, '0')}${ext}`;
    try { if ((await fs.stat(path.join(IMAGE_DIR, filename))).size > 0) return `images/equipment/${filename}`; }
    catch (err) { if (err.code !== 'ENOENT') throw err; }
  }
  return '';
}
async function main() {
  const plan = JSON.parse(await fs.readFile(PLAN_PATH, 'utf8'));
  if (!Array.isArray(plan) || !plan.length || plan.some(p => !p.name || !Number.isInteger(Number(p.equipment_id))) ||
      new Set(plan.map(p => Number(p.equipment_id))).size !== plan.length) {
    throw new Error('Invalid inventory plan; each item must have a unique equipment_id and name.');
  }
  await fs.mkdir(IMAGE_DIR, {recursive: true});
  const mapping = {};
  const rows = [];
  for (const item of plan) {
    const id = Number(item.equipment_id);
    const query = [item.name, item.description, 'product photo'].filter(Boolean).join(' ');
    const url = `https://www.pinterest.com/search/pins/?q=${encodeURIComponent(query)}`;
    const photo = await existingImage(id);
    if (photo) mapping[id] = photo;
    rows.push({id, name: item.name, description: item.description || '', url, photo});
  }
  await fs.writeFile(MAP_PATH, '// BorrowBox equipment-ID photo map. Generated by download_equipment_photos.js.\n' +
    'window.BORROWBOX_EQUIPMENT_PHOTOS = ' + JSON.stringify(mapping, null, 2) + ';\n');
  const tr = rows.map(r => `<tr><td>${r.id}</td><td><strong>${esc(r.name)}</strong><br><small>${esc(r.description)}</small></td><td><a target="_blank" rel="noopener noreferrer" href="${esc(r.url)}">Search Pinterest ↗</a></td><td>${r.photo ? `<img loading="lazy" src="frontend/${esc(r.photo)}" alt="Current photo">` : '<span class="missing">Missing</span>'}</td><td><code>${String(r.id).padStart(2,'0')}.jpg</code></td></tr>`).join('\n');
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>BorrowBox Pinterest Photo Checklist</title><style>body{background:#07162c;color:#eef5ff;font:15px system-ui,sans-serif;margin:0;padding:30px}main{max-width:1100px;margin:auto}h1{margin-bottom:6px}p{line-height:1.6;color:#c5d3ed}table{border-collapse:collapse;width:100%;background:#102641}th,td{border-bottom:1px solid #304866;padding:12px;text-align:left;vertical-align:middle}a{color:#7bb0ff}img{width:96px;height:70px;object-fit:contain;background:#fff;border-radius:5px}.missing{color:#ffbf95}small{color:#acbfdb}code{white-space:nowrap;color:#70e3cc}@media(max-width:700px){body{padding:12px}td,th{padding:7px;font-size:12px}}</style></head><body><main><h1>BorrowBox — Pinterest photo checklist</h1><p>Click a search for each equipment item, then select a photograph that accurately matches its description and whose owner permits reuse. Download/save it to <code>frontend/images/equipment/</code>, naming it exactly as in the right column (JPEG recommended). Replace incorrect existing pictures, too. Pinterest pins are not automatically licensed for reuse. Rerun <code>node download_equipment_photos.js</code> to refresh the image map; then commit images and JS to GitHub.</p><p><strong>${Object.keys(mapping).length} of ${plan.length} image files currently present.</strong> Existing files may still be incorrect—inspect thumbnails.</p><table><thead><tr><th>ID</th><th>Inventory item</th><th>Search</th><th>Existing file preview</th><th>Save photo as</th></tr></thead><tbody>${tr}</tbody></table></main></body></html>`;
  await fs.writeFile(REVIEW_PATH, html);
  await fs.writeFile(CSV_PATH, [['equipment_id','name','description','pinterest_search','local_image','suggested_filename'].join(','),...rows.map(r=>[r.id,r.name,r.description,r.url,r.photo,`${String(r.id).padStart(2,'0')}.jpg`].map(csv).join(','))].join('\n')+'\n');
  console.log(`Prepared Pinterest searches for ${plan.length} items; ${Object.keys(mapping).length} image files present.`);
  console.log(`Open: ${REVIEW_PATH}`);
  console.log('Mac: open pinterest-photo-review.html');
  console.log('Save permitted photos with the ID filenames, then rerun this command.');
}
main().catch(err => { console.error(err.message); process.exitCode = 1; });
